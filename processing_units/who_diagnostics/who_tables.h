// ============================================================================
// HIGH-SPEED O(1) INTERPOLATION ENGINE
// ============================================================================
inline LMS_Params getInterpolatedLMS(float lengthCm, bool isMale) {
    LMS_Params result;

    // 1. Clamp input within table bounds
    if (lengthCm < 45.0f) lengthCm = 45.0f;
    if (lengthCm > 110.0f) lengthCm = 110.0f;

    // 2. Direct O(1) Index Calculation
    float rawIndex = (lengthCm - 45.0f) / 0.5f;
    int index = (int)rawIndex;
    
    // Fractional step for linear interpolation
    float factor = rawIndex - (float)index;

    // Maximum index check (131 entries -> index 0 to 130)
    if (index >= 130) {
        index = 129;
        factor = 1.0f;
    }

    // 3. Pointer selection based on sex
    const LMS_Entry* table = isMale ? WHO_WLZ_BOYS : WHO_WLZ_GIRLS;

    // 4. Safely read Flash memory (PROGMEM)
    LMS_Entry p1, p2;
    p1.L = pgm_read_float(&(table[index].L));
    p1.M = pgm_read_float(&(table[index].M));
    p1.S = pgm_read_float(&(table[index].S));

    p2.L = pgm_read_float(&(table[index + 1].L));
    p2.M = pgm_read_float(&(table[index + 1].M));
    p2.S = pgm_read_float(&(table[index + 1].S));

    // 5. Two-Point Linear Interpolation Formula
    result.L = p1.L + factor * (p2.L - p1.L);
    result.M = p1.M + factor * (p2.M - p1.M);
    result.S = p1.S + factor * (p2.S - p1.S);

    return result;
}

